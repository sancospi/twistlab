// node scripts/daily-scrambles.js [YYYY-MM-DD] [days]: writes the daily challenge's pool, api/_lib/daily-scrambles.js:
// `days` random-state 3x3 scrambles (cubing.js, as WCA's), one a day from the date (default: today, UTC). Regenerating
// changes every day's scramble from that date on: start it tomorrow, or today's players get a new one mid-day.
import { writeFileSync } from 'node:fs';
import { randomScrambleForEvent } from 'cubing/scramble';

const start = process.argv[2] ?? new Date().toISOString().slice(0, 10);
const days = Number(process.argv[3] ?? 800);
if (!/^\d{4}-\d{2}-\d{2}$/.test(start) || !(days > 0)) throw new Error('usage: node scripts/daily-scrambles.js [YYYY-MM-DD] [days]');
const scrambles = [];
for (let i = 0; i < days; i++) scrambles.push((await randomScrambleForEvent('333')).toString());
writeFileSync(new URL('../api/_lib/daily-scrambles.js', import.meta.url), `// Generated by scripts/daily-scrambles.js: the daily challenge's scrambles (api/daily.js), one a day from START (UTC),
// then again from the first. Server only: never import it from src/ (the client bundle would carry every future scramble).
export const START = '${start}';
export const SCRAMBLES = [
${scrambles.map((s) => `  ${JSON.stringify(s)},`).join('\n')}
];
`);
console.log(`${days} scrambles from ${start}`);
process.exit(0); // cubing's search worker would keep node running
